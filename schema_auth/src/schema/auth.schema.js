import mongoose, { Schema } from "mongoose";

const authSchema = new Schema(
  {
    name: {
      type: String,
      required: true,
    },
    email: {
      type: String,
      required: true,
      unique: true,
    },
    password: {
      type: String,
      required: true,
    },
  },
  { timestamps: true },
);

const auth = mongoose.model("auth", authSchema);

export default auth;
