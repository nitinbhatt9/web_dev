// convert the string "Hello" to UpperCase.

let msg = "hello";
console.log(msg.toUpperCase());

// convert the string "Hello" to LowerCase.

let msgs = "hello";
console.log(msgs.toLowerCase());

// remove extra space form "hello".

let sms = "   hello";
console.log(sms.trim());
console.log(sms);

